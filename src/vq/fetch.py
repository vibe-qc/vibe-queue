class FetchMetadataCollisionError(ValueError):
    """Raw payload would be replaced by generated fetch-control metadata."""


def _metadata_collision(path: object, reason: str) -> FetchMetadataCollisionError:
    return FetchMetadataCollisionError(f"fetch metadata collision at {path}: {reason}")


def _check_raw_fetch_metadata(root: Path) -> None:
    """Protect raw bytes while permitting ordinary _vq lifecycle records."""
    metadata = root / "_vq"
    try:
        mode = metadata.lstat().st_mode
    except FileNotFoundError:
        return
    if not stat.S_ISDIR(mode):
        raise _metadata_collision(metadata, "reserved _vq namespace is not a real directory")
    for relative in sorted(_FETCH_CONTROL_SIDECARS):
        path = root / relative
        try:
            path.lstat()
        except FileNotFoundError:
            continue
        raise _metadata_collision(path, "raw payload occupies a generated fetch sidecar")


def _fetch_control_member(member: tarfile.TarInfo, root: str) -> str | None:
    """Identify logical control paths before extracting tar aliases or links."""
    normalized = posixpath.normpath(member.name)
    prefix = root + "/"
    if not normalized.startswith(prefix):
        return None  # The unchanged data filter handles out-of-root members.
    relative = normalized[len(prefix):]
    if relative == "_vq" and not member.isdir():
        raise _metadata_collision(member.name, "reserved _vq namespace is not a directory")
    for control in sorted(_FETCH_CONTROL_SIDECARS):
        if relative == control:
            return control
        if relative.startswith(control + "/"):
            raise _metadata_collision(member.name, "generated fetch sidecar is a payload directory")
    return None


# Exclusion stages, recorded per entry so an operator can tell WHERE the entry
# was lost — on the host that holds the workspace, or on the laptop unpacking
# it. `remote stderr: (empty)` used to be the only clue for the latter.
