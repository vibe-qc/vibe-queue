def _add_exclusions_sidecar_to_tar(
    tf: tarfile.TarFile,
    *,
    arcname_root: str,
    jobid: str,
    exclusions: list[FetchExclusion],
) -> None:
    """Carry the emitter's "could not archive this" list inside the tarball.

    The emitter usually runs on the far side of an ssh pipe, where its stderr
    is only surfaced when the transfer FAILS. A successful partial transfer
    therefore has to state its own gaps in-band, as a tar member.
    """
