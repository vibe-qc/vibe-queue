# FETCH-FRESHNESS (issues #111 / #114).
#
# Every fetched tree carries this manifest so a consumer can age-check the
# payload WITHOUT trusting the CLI's exit code or its "fetched -> ..." line.
# The loop's mandated terminal-detection method is results-presence
# (LEARNINGS L37) precisely because scheduler state is unreliable; a fetched
# tree with no recorded fetch time makes results-presence unreliable in the
# same silent direction. `fetched_at` answers "how old is what I am reading",
# and `stale` / `refresh_error` answer "did the last fetch actually land".
FETCH_MANIFEST_SIDECAR = "_vq/fetch-manifest.json"
FETCH_MANIFEST_SCHEMA = "vq.fetch-manifest.v1"

# PARTIAL FETCH (#62).
#
# A workspace is not always wholly readable or wholly safe to unpack: a
# multi-user job root can hold files the fetching account cannot read, and a
# job may legitimately symlink out of its workspace, which the tar extraction
# filter refuses (correctly — an absolute link is a path-traversal primitive).
# Both used to abort the WHOLE job: `tf.add()` raises on the first unreadable
# file and one refused member failed the entire extraction, so the job was
# fetched completely or not at all.
#
# Now every entry vq cannot carry is skipped and NAMED here, on both sides of
# the wire: the emitter records what it could not read or could not safely
# archive, the receiver records what the extraction filter refused. The tree
# still lands, and this sidecar is the manifest of what is missing from it, so
# a downstream analysis can state its own coverage instead of mistaking an
# unreadable file for a scientific gap.
FETCH_EXCLUSIONS_SIDECAR = "_vq/fetch-exclusions.json"
FETCH_EXCLUSIONS_SCHEMA = "vq.fetch-exclusions.v1"

# These paths are generated by fetch, unlike the other lifecycle records in
# _vq/. Raw workspace/archive bytes at these names must never be overwritten.
_FETCH_CONTROL_SIDECARS = frozenset({
    TERMINAL_DIAGNOSIS_SIDECAR, FETCH_MANIFEST_SIDECAR, FETCH_EXCLUSIONS_SIDECAR,
})
FETCH_PROTOCOL_PAX_KEY = "VQ.fetch-protocol.v1"


