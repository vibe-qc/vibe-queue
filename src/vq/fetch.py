@dataclass(frozen=True)
class FetchExclusion:
    """One workspace entry a fetch deliberately left behind.

    ``path`` is relative to the fetched tree's top-level directory, so it
    names the hole exactly where a consumer would look for it. ``stage`` is
    :data:`EXCLUSION_STAGE_ARCHIVE` (the host holding the workspace could not
    read or could not safely archive it) or :data:`EXCLUSION_STAGE_EXTRACT`
    (the receiving side's tar filter refused it). ``reason`` is a stable
    machine-comparable token; ``detail`` is the human sentence.
    """

    path: str
    stage: str
    reason: str
    detail: str

    def as_dict(self) -> dict[str, str]:
        return {
            "path": self.path,
            "stage": self.stage,
            "reason": self.reason,
            "detail": self.detail,
        }


def _exclusions_payload(
    exclusions: list[FetchExclusion],
    *,
    jobid: str,
    unrecorded: int = 0,
) -> dict[str, object]:
    """Machine-readable record of what this fetch left behind.

    ``unrecorded`` counts entries this side knows were lost but holds no
    record of — the emitter's own list is capped, so a receiver merging it
    must carry the overflow forward as a number instead of letting the cap
    quietly become the total.
    """
    recorded = exclusions[:FETCH_EXCLUSIONS_MAX_RECORDED]
    total = len(exclusions) + max(unrecorded, 0)
    return {
        "schema": FETCH_EXCLUSIONS_SCHEMA,
        "jobid": jobid,
        "generated_at": utcnow_iso(),
        # `excluded_count` is the TRUE total even when `excluded` is capped,
        # so a consumer never reads a truncated list as a complete one.
        "excluded_count": total,
        "recorded_count": len(recorded),
        "truncated": len(recorded) < total,
        "excluded": [item.as_dict() for item in recorded],
    }


def _exclusions_bytes(payload: dict[str, object]) -> bytes:
    return (
        json.dumps(payload, indent=2, sort_keys=True, default=str) + "\n"
    ).encode("utf-8")


def _write_fetch_exclusions(
    dst: Path,
    exclusions: list[FetchExclusion],
    *,
    jobid: str,
    unrecorded: int = 0,
) -> None:
    """Write the exclusion sidecar into a staged tree.

    It is written even when nothing was excluded: an empty list is the
    positive statement "this vq checked, and the tree is complete", which a
    consumer cannot infer from a missing file (a pre-#62 vq wrote none).
    """
    path = dst / FETCH_EXCLUSIONS_SIDECAR
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(
        _exclusions_bytes(
            _exclusions_payload(exclusions, jobid=jobid, unrecorded=unrecorded)
        )
    )


def read_fetch_exclusions(dst: Path) -> dict[str, object] | None:
    """Return the exclusion sidecar of a fetched tree, or None when absent.

    None means "no record", which for a tree fetched by a pre-#62 vq is NOT
    the same as "nothing was excluded" — such a vq would have failed the whole
    job instead. Callers that report coverage must distinguish the two.
    """
    try:
        payload = json.loads(
            (dst / FETCH_EXCLUSIONS_SIDECAR).read_text(encoding="utf-8")
        )
    except (OSError, UnicodeError, json.JSONDecodeError, TypeError):
        return None
    if not isinstance(payload, dict):
        return None
    if payload.get("schema") != FETCH_EXCLUSIONS_SCHEMA:
        return None
    return payload


def excluded_count_for_destination(dst: Path) -> int:
    """How many entries the fetch that wrote ``dst`` left behind (0 if none)."""
    payload = read_fetch_exclusions(dst)
    if payload is None:
        return 0
    count = payload.get("excluded_count")
    return count if isinstance(count, int) and count > 0 else 0


def _exclusions_from_sidecar_payload(
    payload: object,
) -> tuple[list[FetchExclusion], int]:
    """Rebuild exclusion records from a sidecar payload, ignoring junk.

    The payload crosses a host boundary, so every field is treated as
    untrusted input: a malformed record is dropped rather than raised on, and
    nothing here is ever used as a filesystem path.

    Returns the rebuilt records AND how many further entries the emitting side
    said it lost but did not list. Its list is capped, so rebuilding only the
    records would let a merge turn "1500 lost, 1000 listed" into a tidy,
    untruncated "1000 lost" — the receiving side would then publish a smaller
    number than the host it fetched from, which is the one failure mode this
    whole sidecar exists to prevent.
    """
    if not isinstance(payload, dict) or payload.get("schema") != FETCH_EXCLUSIONS_SCHEMA:
        return [], 0
    raw = payload.get("excluded")
    if not isinstance(raw, list):
        return [], 0
    rebuilt: list[FetchExclusion] = []
    for item in raw[:FETCH_EXCLUSIONS_MAX_RECORDED]:
        if not isinstance(item, dict):
            continue
        fields = {
            key: item.get(key)
            for key in ("path", "stage", "reason", "detail")
        }
        if not all(isinstance(value, str) for value in fields.values()):
            continue
        rebuilt.append(
            FetchExclusion(
                path=str(fields["path"])[:512],
                stage=str(fields["stage"])[:64],
                reason=str(fields["reason"])[:64],
                detail=str(fields["detail"])[:512],
            )
        )
    declared = payload.get("excluded_count")
    if isinstance(declared, bool) or not isinstance(declared, int):
        return rebuilt, 0
    return rebuilt, max(declared - len(rebuilt), 0)


