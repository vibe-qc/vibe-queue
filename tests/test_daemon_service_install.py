"""`vq daemon install`: the daemon's unit gets an owner.

`vq web install` writes and refreshes the console's systemd unit. There was no
equivalent for the daemon, so across the reference fleet its units disagreed:
one referenced `%h/.local/bin/vq`, two hardcoded a pre-split venv path.
Repointing `~/.local/bin/vq` moved the first host and left the other two
running the old vq after a restart, with their config and their symlink both
looking correct. Only `vq doctor`'s `daemon_rpc` version revealed it.
"""
from __future__ import annotations

import json
import plistlib
import subprocess
from pathlib import Path

import pytest
from click.testing import CliRunner

from vq import config, paths
from vq.cli import main
from vq.web import install


@pytest.fixture
def host(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    executable = tmp_path / "venv" / "bin" / "vq"
    executable.parent.mkdir(parents=True)
    executable.write_text("#!/bin/sh\n", encoding="utf-8")
    executable.chmod(0o755)
    monkeypatch.setattr(
        install,
        "resolve_service_command",
        lambda kind: [str(executable), *kind.verb],
    )
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path / "xdg"))
    monkeypatch.setenv(paths.ENV_STATE_DIR, str(tmp_path / "state"))
    monkeypatch.setenv(config.ENV_CONFIG_DIR, str(tmp_path / "config"))
    (tmp_path / "state").mkdir()
    (tmp_path / "config").mkdir()
    return tmp_path


def _unit_path(host: Path) -> Path:
    return host / "xdg" / "systemd" / "user" / "vq-daemon.service"


def _write_unit(host: Path, exec_start: str) -> Path:
    path = _unit_path(host)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "[Unit]\nDescription=vq job queue daemon\n"
        f"[Service]\nExecStart={exec_start}\n",
        encoding="utf-8",
    )
    return path


class TestGeneratedUnit:
    def test_it_points_at_the_vq_that_installed_it(self, host: Path) -> None:
        """Not at `vq` on PATH: a user unit has a different PATH than the
        shell you typed in, which is how two hosts kept a pre-split venv."""
        plan = install.build_plan(
            manager="systemd-user", kind=install.DAEMON_SERVICE,
        )
        unit = plan.writes[0].content

        assert plan.unit_name == "vq-daemon"
        assert f'ExecStart="{host / "venv" / "bin" / "vq"}" "daemon" "run"' in unit
        assert "Description=vq job queue daemon" in unit

    def test_the_unit_carries_no_capacity_caps(self, host: Path) -> None:
        plan = install.build_plan(
            manager="systemd-user", kind=install.DAEMON_SERVICE,
        )
        unit = plan.writes[0].content

        exec_line = next(
            line for line in unit.splitlines() if line.startswith("ExecStart=")
        )
        for flag in install.DAEMON_CAP_FLAGS:
            assert flag not in exec_line

    def test_the_unit_explains_itself_as_a_daemon_unit(self, host: Path) -> None:
        """A console header on a daemon unit misinforms whoever is debugging
        it at 2am."""
        unit = install.build_plan(
            manager="systemd-user", kind=install.DAEMON_SERVICE,
        ).writes[0].content

        assert "generated by `vq daemon install`" in unit
        assert "[daemon]" in unit
        assert "vq web install" not in unit
        assert "[web]" not in unit

    def test_the_console_unit_is_unchanged(self, host: Path) -> None:
        unit = install.build_plan(manager="systemd-user").writes[0].content

        assert "generated by `vq web install`" in unit
        assert '"web" "run"' in unit

    def test_the_two_services_do_not_share_a_marker(self, host: Path) -> None:
        """A marker read as the wrong service would report the wrong owner."""
        console = install.build_plan(manager="systemd-user")
        daemon = install.build_plan(
            manager="systemd-user", kind=install.DAEMON_SERVICE,
        )

        console_marker = console.final_writes[0]
        daemon_marker = daemon.final_writes[0]
        assert console_marker.path != daemon_marker.path
        assert "console_command" in json.loads(console_marker.content)
        assert "daemon_command" in json.loads(daemon_marker.content)


